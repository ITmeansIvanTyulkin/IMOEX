/**
 * Итоговое решение после техники + новостного фильтра.
 */
public enum FinalTradeDecision {
    /** Техсигнал подтверждён — можно входить базовым размером. */
    ENTER,
    /** Вход допустим, но размер уменьшить из‑за caution-триггеров. */
    REDUCE_SIZE,
    /** Не входить сейчас — наблюдать. */
    WATCH,
    /** Вход запрещён (делистинг, стоп торгов, санкции, протухшие данные и т.п.). */
    BLOCK
}
